/**
 * Faithfulness 評価プロンプト。
 *
 * Nova Pro に Wikipedia 抜粋と生成文を提示し、抜粋に裏付けられない固有名詞・事実が
 * 混入していないかを採点させる。
 *
 * @param {object} params
 * @param {string} params.prefecture
 * @param {string} params.municipality
 * @param {string} params.description - 採点対象の生成文
 * @param {string} params.wikipediaExtract - cleanExtract 適用済の Wikipedia 抜粋
 * @returns {string}
 */
export function buildFaithfulnessPrompt({
  prefecture,
  municipality,
  description,
  wikipediaExtract,
}) {
  return `あなたは厳格な校閲者です。以下の市町村要約（${prefecture} ${municipality}）が、提供された Wikipedia 抜粋にどれだけ忠実かを採点します。

【手順】
1. 要約本文に含まれる固有名詞・事実（地名・人物名・年号・特産品・施設名・歴史事実）を抽出する
2. それぞれが Wikipedia 抜粋に明示的に書かれているか照合する
3. **抜粋に書かれていない固有名詞・事実があれば、out_of_kb_terms に列挙する**
4. 採点基準に従い 1〜5 のスコアを付ける
5. 必ず以下の JSON 形式のみで出力する（前後に説明文を付けない）:
   {"out_of_kb_terms": ["抜粋にない固有名詞1", "..."], "score": <整数 1-5>, "notes": "<簡潔なまとめ 50 字以内>"}

【採点基準】
- 5: 要約に含まれる固有名詞・事実がすべて抜粋に書かれている。完全に忠実
- 4: 抜粋に書かれていない要素が 1 つだけあるが、地理常識として明らかな矛盾はない（許容範囲）
- 3: 抜粋にない固有名詞が 2-3 個ある。再生成すべき
- 2: 抜粋にない事実が複数あり、創作の疑いが強い
- 1: 抜粋に書かれていない事実だらけ、または抜粋と直接矛盾する記述あり

【評価しないこと】
- 文体の良し悪し（「です・ます調か」「カーナビ風か」は別軸の話）
- 字数の過不足（別途文字数チェックで担保）
- 要約の包括性（抜粋のどの部分を選んだかは問わない）

【Wikipedia 抜粋】
${wikipediaExtract}

【採点対象の要約】
${description}

【Few-shot 例】

例 A（5 点想定、完全に忠実）:
要約: 「函館市は北海道渡島地方の南部に位置する中核市です。1859 年に国際貿易港として開港した函館港を有し、明治期には外国人居留地が形成されました。函館山からの夜景は世界三大夜景の一つに数えられます。」
（抜粋: 「函館市は、北海道渡島地方南部に位置する中核市である。1859年に開港した国際貿易港・函館港を有し、明治期には外国人居留地が形成された。函館山からの夜景は世界三大夜景の一つとされる。」）
→ 出力: {"out_of_kb_terms": [], "score": 5, "notes": "抜粋の事実だけで構成、完全に忠実"}

例 B（2 点想定、抜粋にない事実を捻り出している）:
要約: 「海老名市は神奈川県中部の県央地域に位置する市で、1971 年 11 月 1 日に市制施行し、人口は約 14 万人である。市内には小田急線と JR 相模線が交差する海老名駅があり、交通の要所となっている。タマネギやメロンの出荷が本格化する時期である。」
（抜粋: 「海老名市は、神奈川県中部の県央地域に位置する市で、神奈川県の中央部に位置する。」）
→ 出力: {"out_of_kb_terms": ["1971 年 11 月 1 日に市制施行", "人口は約 14 万人", "小田急線", "JR 相模線", "海老名駅", "タマネギ", "メロン"], "score": 2, "notes": "抜粋にない固有名詞と特産品が複数混入、創作の疑い強い"}

ではこの要約を採点してください。`;
}
